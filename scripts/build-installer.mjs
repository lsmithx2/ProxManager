import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const read=path=>readFileSync(new URL(path,root));
export function installer(){
 const bundle=Object.fromEntries(['agent.py','proxmanager.service'].map(name=>{
  const data=read('agent/'+name);
  return [name,{content:data.toString('base64'),sha256:createHash('sha256').update(data).digest('hex')}];
 }));
 // No top-level mutations: a truncated download cannot start a partial install.
 return `#!/bin/bash\n# Generated by scripts/build-installer.mjs; edit agent/installer.py instead.\n# Agent and service are embedded from the same source revision.\nset -euo pipefail\nproxmanager_install() {\n  /usr/bin/python3 - <<'PROXMANAGER_PYTHON'\n${read('agent/installer.py').toString('utf8')}\nmain(json.loads(base64.b64decode('${Buffer.from(JSON.stringify(bundle)).toString('base64')}')))\nPROXMANAGER_PYTHON\n}\nproxmanager_install "$@"\n`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const output=new URL('public/install.sh',root),source=installer();
 if(process.argv.includes('--check')){
  if(readFileSync(output,'utf8')!==source)throw new Error('Installer is stale: run npm run build');
 }else writeFileSync(output,source);
}
